/**
 * Generates `_headers` (Cloudflare Pages) and `netlify.toml` from the built
 * output, with a Content-Security-Policy whose script hashes are computed from
 * the bytes actually served.
 *
 * Hashing the built HTML rather than the source is the point. If Astro changes
 * how it emits an inline script — whitespace, ordering, anything — a
 * source-derived hash silently stops matching and the script is blocked in
 * production while every local check still passes. Reading dist removes that
 * whole class of failure.
 *
 * 'unsafe-inline' and 'unsafe-eval' are never emitted. If a script appears that
 * cannot be hashed, this script fails the build rather than widening the policy.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const DIST = 'dist';

const htmlFiles = (dir) => {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...htmlFiles(full));
    else if (name.endsWith('.html')) out.push(full);
  }
  return out;
};

const files = htmlFiles(DIST);
if (files.length === 0) {
  console.error('No HTML in dist. Run the build first.');
  process.exit(1);
}

/**
 * Collect every inline script body.
 *
 * Matches only scripts with no `src`, since an external script is covered by
 * `script-src 'self'` and needs no hash.
 */
const hashes = new Map();
const inlineScript = /<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g;

for (const file of files) {
  const html = readFileSync(file, 'utf8');
  for (const [, attrs, body] of html.matchAll(inlineScript)) {
    // JSON-LD is data, not executable script, and is not covered by script-src.
    if (/type\s*=\s*["']application\/ld\+json["']/i.test(attrs)) continue;
    if (body.trim() === '') continue;

    const hash = createHash('sha256').update(body, 'utf8').digest('base64');
    if (!hashes.has(hash)) {
      hashes.set(hash, { count: 0, sample: body.trim().slice(0, 60), file: relative(DIST, file) });
    }
    hashes.get(hash).count += 1;
  }
}

const scriptHashes = [...hashes.keys()].map((hash) => `'sha256-${hash}'`).join(' ');

/**
 * The policy from section 11, with the computed hashes substituted.
 *
 * `style-src 'self'` with no hashes is possible because `inlineStylesheets:
 * 'never'` keeps every stylesheet external and no element carries a style
 * attribute — the html-validate `no-inline-style` rule enforces the second half
 * of that, and it caught Shiki emitting inline styles on code blocks.
 */
const csp = [
  "default-src 'none'",
  `script-src 'self'${scriptHashes === '' ? '' : ` ${scriptHashes}`}`,
  "style-src 'self'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  "manifest-src 'self'",
  "form-action 'none'",
  "frame-ancestors 'none'",
  "base-uri 'none'",
  "object-src 'none'",
  'upgrade-insecure-requests',
].join('; ');

const HEADERS = [
  ['Content-Security-Policy', csp],
  ['Strict-Transport-Security', 'max-age=63072000; includeSubDomains; preload'],
  ['X-Content-Type-Options', 'nosniff'],
  ['Referrer-Policy', 'strict-origin-when-cross-origin'],
  [
    'Permissions-Policy',
    'geolocation=(), camera=(), microphone=(), payment=(), usb=(), interest-cohort=()',
  ],
  ['Cross-Origin-Opener-Policy', 'same-origin'],
  ['Cross-Origin-Resource-Policy', 'same-origin'],
  ['X-Frame-Options', 'DENY'],
];

// --- Cloudflare Pages _headers ----------------------------------------------
const headersFile = [
  '# Generated by scripts/generate-headers.mjs during the build. Do not edit.',
  '# Script hashes are computed from the built HTML, so they always match what',
  '# is actually served.',
  '',
  '/*',
  ...HEADERS.map(([name, value]) => `  ${name}: ${value}`),
  '',
  '# Fingerprinted assets are immutable: the filename changes when content does.',
  '/_astro/*',
  '  Cache-Control: public, max-age=31536000, immutable',
  '',
  '# Generated images are not fingerprinted, so they get a shorter window.',
  '/og/*',
  '  Cache-Control: public, max-age=86400',
  '',
].join('\n');

writeFileSync(join(DIST, '_headers'), headersFile);

// --- Netlify fallback --------------------------------------------------------
const toml = [
  '# Netlify configuration, documented as the fallback host in DEPLOY.md.',
  '# Regenerated by scripts/generate-headers.mjs; the CSP hashes below come from',
  '# the built output and change whenever an inline script does.',
  '',
  '[build]',
  '  command = "npm run build"',
  '  publish = "dist"',
  '',
  '[build.environment]',
  '  NODE_VERSION = "22"',
  '',
  '[[headers]]',
  '  for = "/*"',
  '  [headers.values]',
  ...HEADERS.map(([name, value]) => `    ${name} = "${value.replace(/"/g, '\\"')}"`),
  '',
  '[[headers]]',
  '  for = "/_astro/*"',
  '  [headers.values]',
  '    Cache-Control = "public, max-age=31536000, immutable"',
  '',
].join('\n');

writeFileSync('netlify.toml', toml);

console.log(
  `Headers written. ${hashes.size} unique inline script(s) hashed across ${files.length} pages.`
);
for (const [hash, info] of hashes) {
  console.log(`  sha256-${hash.slice(0, 16)}… x${info.count}  ${info.sample.replace(/\s+/g, ' ')}`);
}

// A policy is only as good as its narrowness; flag drift rather than absorbing it.
if (hashes.size > 4) {
  console.error(
    `\n${hashes.size} distinct inline scripts is more than expected. Each one widens the CSP;` +
      ' consider moving them to external files so script-src stays self-only.'
  );
  process.exit(1);
}
